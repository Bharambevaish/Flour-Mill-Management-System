import type { MetadataRoute } from "next";

/**
 * Web App Manifest — this is what turns the customer portal into an installable
 * Android app ("Add to home screen" / "Install app").
 *
 * Must live at the ROOT of `app/`. Next only serves it from there, at
 * `/manifest.webmanifest`; the same file nested deeper is silently ignored.
 *
 * Deliberately NOT a service worker. Per the Next 16 PWA guide, Chrome's
 * install criteria are just a valid manifest plus HTTPS, so there is nothing to
 * gain from caching here — and a cache is a liability on a shared family phone,
 * where a stale cache could show one customer's orders to another.
 *
 * Note there is no `metadata.manifest` in `layout.tsx`. The file convention
 * always wins, so a field there would be dead config that drifts out of sync.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    // Stable identity, so a reinstall updates the existing app instead of
    // installing a second, differently-keyed copy.
    id: "/my",

    name: "Flour Mill",
    // Android prints this under the home-screen icon and truncates past ~12
    // characters. Kept short and Latin so every launcher renders it identically.
    short_name: "Flour Mill",
    description:
      "Flour Mill — order status, payments and outstanding, updated by the mill.",

    lang: "mr",
    dir: "ltr",
    categories: ["business", "food"],

    // Opening the installed app lands on the customer dashboard. `/my` also
    // contains `/my/login`, so a customer whose session expires gets the login
    // screen inside the app instead of being bounced out to a browser tab.
    start_url: "/my",
    scope: "/my",

    // `standalone` hides the browser UI, which is what makes it feel like an app.
    display: "standalone",
    // The portal is a phone-first, scrolling dashboard.
    orientation: "portrait",

    // Matches the light `viewport.themeColor` in layout.tsx so the Android
    // status bar is seamless with the portal surface. The manifest format has
    // no media queries, so dark-mode users also get this pale bar.
    theme_color: "#f6f1e7",
    // Tints the splash screen while the app boots, avoiding a white flash.
    background_color: "#f6f1e7",

    // Generated by `npm run icons`. A missing or wrong-sized icon is the classic
    // reason a browser silently never offers "Install app", so test section 24
    // fetches each one and asserts its real pixel dimensions.
    icons: [
      { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      {
        src: "/icons/icon-maskable-512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };
}
